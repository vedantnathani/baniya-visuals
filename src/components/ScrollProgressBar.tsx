"use client";

import { motion, useScroll, useSpring } from "framer-motion";

export default function ScrollProgressBar() {
  const { scrollYProgress } = useScroll();
  const scaleX = useSpring(scrollYProgress, {
    stiffness: 100,
    damping: 30,
    restDelta: 0.001,
  });

  return (
    <motion.div
      className="fixed top-0 left-0 right-0 h-[2.5px] bg-gradient-to-r from-amber-400 via-accent-gold to-yellow-200 origin-left z-[100] shadow-[0_0_10px_var(--accent-glow)]"
      style={{ scaleX }}
    />
  );
}
